"""Scenario entry points for the admin router."""

import time
from datetime import timedelta

from . import store

__all__ = ["bank_outage", "eval_fixtures"]
bank_outage = store.bank_outage


def eval_fixtures() -> dict:
    """Add the eval ledger (cust_eval_NN, mer_eval_NN, ...) on top of `store.seed()`.

    (decision: data is generated by `evals.make_dataset.build()`, the single source for rows and
    fixtures.) Only adds new ids, never touches canonical seed data. Returns the fixture spec.
    """
    from evals.make_dataset import build

    _, fx = build()
    t = store._base_now()  # (decision: FIX4) replay-stable anchor
    for cid in fx["customers"]:
        store.customers[cid] = {"id": cid, "name": f"Eval Customer {cid[-2:]}", "tier": "standard",
                                "since": "2024-01-01", "language": "en", "phone_masked": "+91 90XXXXXX00"}  # fmt: skip
    for m in fx["merchants"]:
        store.merchants[m["id"]] = {**m, "settlement_cycle": "T+1"}
    for x in fx["transactions"]:
        store._txn(x["id"], x["customer_id"], x["merchant_id"], x["amount_inr"], x["method"],
                   x["status"], x["issuer_bank"], x["failure_reason"],
                   t - timedelta(days=x["age_days"]))  # fmt: skip
        if x["refund_id"]:
            store.transactions[x["id"]].update(refund_id=x["refund_id"],
                                               refund_status=x["refund_status"])  # fmt: skip
    for r in fx["refunds"]:
        pending = r["status"] == "INITIATED"
        store.refunds[r["refund_id"]] = {
            "refund_id": r["refund_id"], "txn_id": r["txn_id"], "amount_inr": r["amount_inr"],
            "arn": r["arn"], "reason": "eval fixture", "status": r["status"],
            # far-future created_ts keeps INITIATED refunds from auto-settling (decision)
            "created_ts": time.time() + 1e9 if pending else 0.0,
            "eta": store.iso(t + timedelta(days=r["eta_days"])),
        }  # fmt: skip
    for s in fx["settlements"]:
        store.settlements[s["id"]] = {
            "id": s["id"], "merchant_id": s["merchant_id"], "amount_inr": s["amount_inr"],
            "status": s["status"], "expected_at": store.iso(t + timedelta(days=s["expected_days"])),
            "reason": s["reason"],
        }  # fmt: skip
    store.kyc.update(fx["kyc"])
    for md in fx["mandates"]:
        store.mandates[md["id"]] = md
    return fx
